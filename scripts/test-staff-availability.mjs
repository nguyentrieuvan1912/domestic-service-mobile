import assert from 'node:assert/strict';
import { createRequire, Module } from 'node:module';
import { readFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const ts = require('typescript');
Module._extensions['.ts'] = (module, filename) => {
  const result = ts.transpileModule(readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } });
  module._compile(result.outputText, filename);
};
const rules = require('../src/data/staffAvailabilityRules.ts');
const { StaffRepository: staff } = require('../src/data/staffRepository.ts');
const { StaffAvailabilityRepository: repo, AVAILABILITY_DEMO_CONFIG: demo, availabilityDraft } = require('../src/data/staffAvailabilityRepository.ts');
const { areaIdsForNames } = require('../src/data/staffAreas.ts');
const hoa = { userId: 'user-s01', staffId: 'staff-001' };
const tuan = { userId: 'user-s05', staffId: 'staff-005' };
const empty = { userId: 'user-s10', staffId: 'staff-010' };
const copy = value => JSON.parse(JSON.stringify(value));
const now = Date.parse('2026-10-08T07:00:00+07:00');
const dates = rules.scheduleDates(now);
assert.deepEqual(dates, ['2026-10-08', '2026-10-09', '2026-10-10', '2026-10-11', '2026-10-12', '2026-10-13', '2026-10-14']);
assert.equal(rules.localDate('2026-10-08T17:00:00Z'), '2026-10-09', 'Midnight is evaluated in Vietnam, not UTC or host timezone');
assert.equal(rules.scheduleDates(Date.parse('2026-10-08T16:59:59Z'))[0], '2026-10-08');
assert.equal(rules.SCHEDULE_TIME_OPTIONS[0], '08:00');
assert.equal(rules.SCHEDULE_TIME_OPTIONS.at(-1), '20:00');
assert.ok(!rules.SCHEDULE_TIME_OPTIONS.includes('08:10'));
const interval = (start, end) => rules.intervalFor(dates[2], start, end);
const normalized = intervals => rules.normalizeDay({ date: dates[2], intervals });
assert.match(normalized([interval('08:10', '10:00')]).error, /30 phút/);
for (const [start, end] of [['10:00', '10:00'], ['11:00', '10:00']]) assert.match(normalized([interval(start, end)]).error, /trước/);
for (const [start, end] of [['07:30', '10:00'], ['19:00', '20:30']]) assert.match(normalized([interval(start, end)]).error, /08:00–20:00/);
assert.match(normalized([{ ...interval('08:00', '10:00'), endsAt: '2026-10-11T10:00:00+07:00' }]).error, /cùng ngày/);
assert.match(normalized([interval('08:00', '11:00'), interval('10:30', '12:00')]).error, /chồng nhau/);
assert.deepEqual(normalized([interval('10:00', '12:00'), interval('08:00', '10:00')]).day.intervals, [interval('08:00', '12:00')]);
assert.equal(rules.intervalContains(interval('08:00', '12:00'), interval('08:00', '12:00')), true);
assert.equal(rules.intervalContains(interval('08:00', '12:00'), interval('11:00', '12:30')), false);
assert.equal(rules.intervalsOverlap(interval('08:00', '10:00'), interval('10:00', '12:00')), false);
const booking = (start, end, id = 'candidate') => ({ ...interval(start, end), id, bookingCode: id, district: 'Bình Thạnh', status: 'ACCEPTED' });
const confirmed = booking('08:00', '10:00', 'confirmed');
const saved = { days: dates.map(date => ({ date, intervals: [rules.intervalFor(date, '08:00', '12:00')] })), areaIds: areaIdsForNames(['Bình Thạnh']), matchNotifications: true };
assert.equal(rules.canScheduleBooking(saved, booking('10:30', '11:30'), [confirmed], now).allowed, false);
assert.equal(rules.canScheduleBooking(saved, booking('11:00', '12:00'), [confirmed], now).allowed, true, 'Exactly 60 minutes after the prior booking is allowed');
assert.equal(rules.bookingWorkMinutes(confirmed), 120, 'Buffer never increases work hours');
assert.equal(Date.parse(rules.bookingBuffer(confirmed).endsAt) - Date.parse(confirmed.endsAt), 60 * 60000);
const fullDay = { ...saved, days: dates.map(date => ({ date, intervals: [rules.intervalFor(date, '08:00', '20:00')] })) };
assert.equal(rules.canScheduleBooking(fullDay, booking('19:00', '20:00'), [], now).allowed, true, 'Default UI policy constrains booking end, not buffer end');
rules.STAFF_SCHEDULE_POLICY.bufferMustEndWithinHours = true;
assert.equal(rules.canScheduleBooking(fullDay, booking('19:00', '20:00'), [], now).allowed, false, 'Optional policy can also constrain the buffer end');
rules.STAFF_SCHEDULE_POLICY.bufferMustEndWithinHours = false;
assert.equal(rules.canScheduleBooking(fullDay, booking('10:00', '11:00'), [booking('12:00', '14:00', 'later')], now).allowed, true, 'Exactly 60 minutes before is allowed');
assert.equal(rules.canScheduleBooking(fullDay, booking('10:30', '11:30'), [booking('12:00', '14:00', 'later')], now).allowed, false);
assert.equal(rules.canScheduleBooking(saved, booking('10:00', '11:00'), [{ ...confirmed, status: 'CANCELLED' }], now).allowed, true);
assert.equal(rules.canScheduleBooking(saved, booking('10:00', '11:00'), [{ ...confirmed, endsAt: 'invalid' }], now).allowed, false);
assert.equal(rules.canScheduleBooking(saved, { ...booking('11:00', '12:00'), district: 'Quận 7' }, [], now).allowed, false);
assert.equal(rules.canScheduleBooking(saved, booking('11:00', '12:30'), [], now).allowed, false, 'Partial containment is insufficient');
assert.equal(rules.canScheduleBooking(saved, booking('11:00', '12:00'), [], Date.parse('2026-10-10T11:00:00+07:00')).allowed, false, 'Cannot receive a job at/past its start');
assert.ok(rules.normalizeDraft(saved, [confirmed], now).draft, 'Availability covers work, not the external buffer');
assert.match(rules.normalizeDraft({ ...saved, areaIds: [] }, [], now).error, /ít nhất/);
assert.match(rules.normalizeDraft({ ...saved, days: saved.days.slice(1) }, [], now).error, /7 ngày/);
const cut = copy(saved); cut.days[2].intervals = [interval('08:00', '09:30')];
assert.match(rules.normalizeDraft(cut, [confirmed], now).error, /đã nhận/);

demo.latencyMs = 1;
await assert.rejects(repo.load({ userId: 'user-c01', staffId: hoa.staffId }), /quyền/);
await assert.rejects(repo.load({ userId: tuan.userId, staffId: hoa.staffId }), /quyền/);
const initial = await repo.load(hoa);
const initialTuan = await repo.load(tuan);
assert.ok(initial.bookings.every(item => item.id !== 'bk-042'));
assert.ok(initialTuan.bookings.every(item => item.id !== 'bk-023'));
assert.equal(initial.unknownBookingCodes.length, 0);
assert.ok((await repo.load(empty)).saved.days.every(day => day.intervals.length === 0));
assert.equal(staff.getOperationalProfile(hoa.staffId).autoAccept, false, 'Deprecated field never enables automatic acceptance');
const beforeRevision = staff.getStoreRevision();
const beforeProfile = staff.getOperationalProfile(hoa.staffId);
const detachedDraft = availabilityDraft(initial);
detachedDraft.days[3].intervals = [];
detachedDraft.matchNotifications = false;
assert.deepEqual(staff.getScheduleSnapshot(hoa.staffId).saved, initial.saved, 'Editing a draft has no saved effect');
assert.equal(staff.getStoreRevision(), beforeRevision);
assert.equal(staff.canReceiveOpportunity(hoa.staffId, 'open-104').allowed, true, 'Uncommitted draft must not affect matching');
assert.equal(staff.canReceiveOpportunity(hoa.staffId, 'open-buffer-1').allowed, false);
assert.equal(staff.canReceiveOpportunity(hoa.staffId, 'open-buffer-2').allowed, true);
const badDraft = availabilityDraft(initial);
badDraft.days[2].intervals = [rules.intervalFor(badDraft.days[2].date, '08:00', '09:30')];
await assert.rejects(repo.save(hoa, badDraft, initial.saved.revision), /đã nhận/);
assert.deepEqual(staff.getOperationalProfile(hoa.staffId), beforeProfile);
assert.deepEqual(staff.getScheduleSnapshot(hoa.staffId).saved, initial.saved);
demo.failNextLoad = true;
await assert.rejects(repo.load(hoa), /Chưa tải/);
assert.ok(await repo.load(hoa));
demo.failNextSave = true;
await assert.rejects(repo.save(hoa, detachedDraft, initial.saved.revision), /Bản nháp/);
assert.deepEqual(staff.getScheduleSnapshot(hoa.staffId).saved, initial.saved);
const controller = new AbortController();
demo.latencyMs = 20;
const abortedSave = repo.save(hoa, detachedDraft, initial.saved.revision, controller.signal);
controller.abort(); await assert.rejects(abortedSave, /Đã hủy/);
assert.deepEqual(staff.getScheduleSnapshot(hoa.staffId).saved, initial.saved);
demo.latencyMs = 1;
let notifications = 0;
const unsubscribe = staff.subscribe(() => notifications++);
const committed = await repo.save(hoa, detachedDraft, initial.saved.revision);
assert.equal(notifications, 1);
assert.equal(committed.saved.revision, initial.saved.revision + 1);
assert.equal(committed.saved.matchNotifications, false);
assert.equal(staff.canReceiveOpportunity(hoa.staffId, 'open-104').allowed, false, 'Matching uses the newly committed schedule');
assert.deepEqual(staff.getScheduleSnapshot(tuan.staffId).saved, initialTuan.saved);
await assert.rejects(repo.save(hoa, availabilityDraft(initial), initial.saved.revision), /nơi khác/);
const withAreaChange = availabilityDraft(committed);
withAreaChange.areaIds = withAreaChange.areaIds.filter(id => !areaIdsForNames(['Quận 1']).includes(id));
const areaCommitted = await repo.save(hoa, withAreaChange, committed.saved.revision);
assert.ok(!staff.getOperationalProfile(hoa.staffId).operatingDistricts.includes('Quận 1'), 'Home profile reads the same committed areas');
const preClaimDraft = availabilityDraft(areaCommitted);
preClaimDraft.days[2].intervals = [rules.intervalFor(preClaimDraft.days[2].date, '08:00', '10:00')];
const walletBefore = staff.getWallet(hoa.staffId);
assert.equal(staff.claimOpportunity(hoa.staffId, 'open-buffer-1').success, false);
assert.equal(staff.claimOpportunity(hoa.staffId, 'open-buffer-2').success, true);
assert.deepEqual(staff.getWallet(hoa.staffId), walletBefore);
await assert.rejects(repo.save(hoa, preClaimDraft, areaCommitted.saved.revision), /đã nhận/, 'Save rechecks a booking received after the draft was read');
assert.equal(staff.getJobDetail(tuan.staffId, 'open-buffer-2').kind, 'FORBIDDEN');
assert.ok(staff.getScheduleSnapshot(hoa.staffId).bookings.some(item => item.id === 'open-buffer-2'));
const rolled = staff.getScheduleSnapshot(hoa.staffId, Date.now() + 86400000);
assert.equal(rolled.saved.days.at(-1).intervals.length, 0, 'A new horizon day does not invent availability');
unsubscribe();
console.log('Availability: timezone/horizon, grid/bounds, normalization, containment/overlap, both buffer boundaries, actor scoping, draft isolation, saved matching, retries/abort, revisions and booking revalidation passed.');
