import assert from 'node:assert/strict';
import { createRequire, Module } from 'node:module';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url), ts = require('typescript');
const originalResolve = Module._resolveFilename;
Module._resolveFilename = function(specifier, parent, ...args) { if (specifier.startsWith('@/')) { const base=resolve('src',specifier.slice(2)); specifier=existsSync(base+'.ts')?base+'.ts':base+'.tsx'; } return originalResolve.call(this,specifier,parent,...args); };
Module._extensions['.ts'] = (module,file) => module._compile(ts.transpileModule(readFileSync(file,'utf8'),{ compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText,file);
const w = require('../src/data/weeklyAvailability.ts'), r = require('../src/data/staffAvailabilityRules.ts');
const now = Date.parse('2026-10-15T10:15:00+07:00');
assert.equal(w.weekStart(now),'2026-10-12');
assert.equal(w.weekStart(Date.parse('2026-10-11T17:00:01Z')),'2026-10-12');
assert.deepEqual(w.weekDates('2026-10-12'),['2026-10-12','2026-10-13','2026-10-14','2026-10-15','2026-10-16','2026-10-17','2026-10-18']);
const day={date:'2026-10-15',intervals:[r.intervalFor('2026-10-15','08:00','12:00')]};
const changed=w.setDaySlots(day,[],now);
assert.deepEqual(changed.intervals,[r.intervalFor(day.date,'08:00','10:30')], 'Removing future time preserves the slot currently in progress');
assert.deepEqual(w.setDaySlots({date:day.date,intervals:[]},w.WEEK_SLOTS,now).intervals,[r.intervalFor(day.date,'10:30','20:00')], 'Cannot add time before clicking edit');
assert.equal(w.slotLocked(day.date,'10:00',now),true);
assert.equal(w.slotLocked(day.date,'10:30',now),false);
assert.deepEqual(w.setDaySlots(day,[],Date.parse('2026-10-16T09:00:00+07:00')),day,'Past days are immutable');
assert.deepEqual(w.intervalsFromSlots(day.date,['08:00','08:30','10:00']),[r.intervalFor(day.date,'08:00','09:00'),r.intervalFor(day.date,'10:00','10:30')]);
assert.equal(day.intervals[0].endsAt,r.intervalFor(day.date,'08:00','12:00').endsAt,'Draft edits do not mutate the original');
const future={date:'2026-10-16',intervals:[]};
const morning=w.toggleShift(future,'08:00','12:00',now);
const two=w.toggleShift(morning,'12:00','17:00',now);
const three=w.toggleShift(two,'17:00','20:00',now);
assert.deepEqual(morning.intervals,[r.intervalFor(future.date,'08:00','12:00')]);
assert.deepEqual(two.intervals,[r.intervalFor(future.date,'08:00','17:00')]);
assert.deepEqual(three.intervals,[r.intervalFor(future.date,'08:00','20:00')]);
assert.deepEqual(w.setDaySlots(future,w.WEEK_SLOTS,now),three,'All-day selects all three shifts');
assert.deepEqual(w.toggleShift(three,'12:00','17:00',now).intervals,[r.intervalFor(future.date,'08:00','12:00'),r.intervalFor(future.date,'17:00','20:00')],'Deselecting one shift keeps the other two');
assert.deepEqual(w.missingRegistrationDates([],now),['2026-10-15','2026-10-16','2026-10-17','2026-10-18']);
assert.deepEqual(w.missingRegistrationDates(['2026-10-12'],now),[],'Completed week suppresses reminder');
assert.equal(w.missingRegistrationDates(['2026-10-12'],Date.parse('2026-10-19T07:00:00+07:00')).length,7,'New week prompts again');
console.log('Weekly schedule: Vietnam calendar week, all seven days, locked past/ongoing slots, future edits and draft isolation passed.');
